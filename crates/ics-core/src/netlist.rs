use crate::connectivity::{Connectivity, extract};
use crate::schematic::{DeviceKind, Instance, Schematic};
use crate::sim_setup::SimSetup;
use crate::tech::{LengthUnit, Tech};
use crate::units::parse_spice;

/// Generic default device models (level-1 style) used when no PDK models are given.
pub const DEFAULT_MODELS: &str = "\
.model nmos nmos (level=1 vto=0.45 kp=280u lambda=0.08 gamma=0.4 phi=0.8 tox=4n cgso=0.3n cgdo=0.3n cj=1m cjsw=0.3n)
.model pmos pmos (level=1 vto=-0.45 kp=70u lambda=0.1 gamma=0.4 phi=0.8 tox=4n cgso=0.3n cgdo=0.3n cj=1m cjsw=0.3n)
.model dmod d (is=1e-14 n=1 rs=10 cjo=1p)";

/// Channel length (m) at which the generic models' `lambda` holds. SPICE level 1 has no
/// channel-length dependence of the output conductance, so the netlister writes a card per
/// drawn L with `lambda` scaled by `LAMBDA_REF_L / L` (named [`generic_card_name`]): longer
/// devices get a higher output resistance and more gain, as in silicon, and the deck stays
/// plain level 1 for any simulator.
pub const LAMBDA_REF_L: f64 = 0.5e-6;

/// Name of the generic model card for `base` (`nmos` / `pmos`) at channel length `l` (m):
/// `nmos__l180` for 180 nm, or `base` itself at [`LAMBDA_REF_L`].
pub fn generic_card_name(base: &str, l: f64) -> String {
    let nm = (l * 1e9).round() as i64;
    if nm == (LAMBDA_REF_L * 1e9).round() as i64 { base.to_string() } else { format!("{base}__l{nm}") }
}

/// The channel length (m) of a generic per-L card name (`nmos__l180` -> 180 nm).
pub fn generic_card_length(name: &str) -> Option<f64> {
    let (_, nm) = name.rsplit_once("__l")?;
    nm.parse::<i64>().ok().filter(|n| *n > 0).map(|n| n as f64 * 1e-9)
}

/// The generic card `base` copied as `name` with `lambda` scaled for channel length `l`.
fn generic_card(base: &str, name: &str, l: f64) -> Option<String> {
    let line = DEFAULT_MODELS.lines().find(|x| x.split_whitespace().nth(1) == Some(base))?;
    let lambda = line.split_whitespace().find_map(|t| t.strip_prefix("lambda="))?.parse::<f64>().ok()?;
    let scaled = format!("lambda={:.6e}", lambda * LAMBDA_REF_L / l);
    Some(line.replacen(&format!(".model {base} "), &format!(".model {name} "), 1).replacen(
        &format!("lambda={lambda}"),
        &scaled,
        1,
    ))
}

/// Bipolar models for NPN / PNP devices placed with the default model names.
pub const DEFAULT_BJT_MODELS: &str = "\
.model npn npn (is=1e-16 bf=100 br=1 vaf=50 rb=100 re=1 rc=10 cje=0.5p cjc=0.3p tf=0.2n)
.model pnp pnp (is=5e-17 bf=50 br=1 vaf=30 rb=100 re=1 rc=10 cje=0.5p cjc=0.3p tf=0.5n)";

#[derive(Debug, Clone)]
pub struct Netlist {
    /// Element and model lines (no analyses / no .end), with the plain model names.
    pub body: String,
    /// Generic per-L model cards for simulation decks: (element name, card name) and the cards
    /// (see [`LAMBDA_REF_L`]). [`Netlist::deck`] applies them; `body` stays as drawn for
    /// netlists that name devices by type (CDL, LVS).
    pub generic: Vec<(String, String)>,
    pub generic_cards: Vec<String>,
    pub warnings: Vec<String>,
    pub conn: Connectivity,
}

impl Netlist {
    /// Full deck including the dot analyses, suitable for any SPICE simulator.
    pub fn deck(&self, title: &str, setup: &SimSetup) -> String {
        let mut s = format!("* {title}\n* Generated by IC Studio\n");
        s += &self.sim_body();
        if !setup.extra.trim().is_empty() {
            s += "\n* --- user lines ---\n";
            s += setup.extra.trim();
            s += "\n";
        }
        s += &format!(".temp {}\n", setup.temp);
        for a in setup.enabled() {
            s += &format!(".{}\n", a.spice_command());
        }
        s += ".end\n";
        s
    }
}

impl Netlist {
    /// `body` with the generic per-L model cards applied (what a simulation runs).
    pub fn sim_body(&self) -> String {
        if self.generic.is_empty() {
            return self.body.clone();
        }
        let mut out = String::with_capacity(self.body.len() + 256);
        for line in self.body.lines() {
            let mut t: Vec<&str> = line.split_whitespace().collect();
            match self.generic.iter().find(|(e, _)| t.first() == Some(&e.as_str())) {
                Some((_, card)) if t.len() > 5 => {
                    t[5] = card;
                    out += &t.join(" ");
                }
                _ => out += line,
            }
            out.push('\n');
        }
        out += "* generic models: lambda scaled by 0.5u / L (level 1 has no channel-length modulation of its own)\n";
        for c in &self.generic_cards {
            out += c;
            out.push('\n');
        }
        out
    }
}

/// Netlist languages a cell can be written in.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Format {
    /// SPICE deck with models and analyses (ngspice, HSPICE).
    Spice,
    /// The same deck in the Spectre language.
    Spectre,
    /// CDL for LVS: a `.SUBCKT` of the devices without sources, models and analyses.
    Cdl,
}

impl std::str::FromStr for Format {
    type Err = String;
    fn from_str(s: &str) -> Result<Self, String> {
        match s.to_ascii_lowercase().as_str() {
            "spice" | "hspice" | "sp" | "cir" => Ok(Format::Spice),
            "spectre" | "scs" => Ok(Format::Spectre),
            "cdl" => Ok(Format::Cdl),
            other => Err(format!("unknown netlist format '{other}' (spice, spectre, cdl)")),
        }
    }
}

/// `sch` as a netlist in `format`, titled `title` (the subcircuit name for CDL), with the
/// netlister's warnings.
pub fn write(sch: &Schematic, tech: &Tech, setup: &SimSetup, title: &str, format: Format) -> (String, Vec<String>) {
    let nl = netlist_for(sch, tech, &setup.corner);
    let text = match format {
        Format::Spice => nl.deck(title, setup),
        Format::Spectre => crate::spectre::from_spice(&nl.deck(title, setup)),
        Format::Cdl => {
            let top: String = title.chars().map(|c| if c.is_ascii_alphanumeric() || c == '_' { c } else { '_' }).collect();
            crate::signoff::cdl(sch, tech, &top)
        }
    };
    (text, nl.warnings)
}

/// The element name the netlist gives voltage source instance `name` (see [`spice_name`]):
/// what an F / H source refers to.
fn vsource_name(name: &str) -> String {
    let n = name.trim().replace(' ', "_");
    if n.starts_with(['v', 'V']) { n } else { format!("V{n}") }
}

pub(crate) fn spice_name(inst: &Instance) -> String {
    let prefix = inst.kind.spice_prefix().unwrap_or('X');
    let name = inst.name.trim().replace(' ', "_");
    if name.chars().next().is_some_and(|c| c.eq_ignore_ascii_case(&prefix)) { name } else { format!("{prefix}{name}") }
}

/// `v` with up to 6 decimals and no trailing zeros.
fn fmt_num(v: f64) -> String {
    let s = format!("{v:.6}");
    s.trim_end_matches('0').trim_end_matches('.').to_string()
}

/// Element name of `inst` in a deck for `tech`: PDK subcircuit MOS models get an `X` prefix.
pub fn element_name(inst: &Instance, tech: &Tech) -> String {
    let name = spice_name(inst);
    match inst.kind {
        DeviceKind::Nmos | DeviceKind::Pmos | DeviceKind::Nmos3 | DeviceKind::Pmos3
            if tech.mos_device(inst.kind.is_pmos(), inst.param("model")).is_some_and(|d| d.subckt) =>
        {
            format!("X{name}")
        }
        _ => name,
    }
}

fn source_spec(inst: &Instance) -> String {
    let mut parts = vec![];
    let dc = inst.param("dc").trim();
    parts.push(format!("DC {}", if dc.is_empty() { "0" } else { dc }));
    let ac = inst.param("ac").trim();
    if !ac.is_empty() {
        parts.push(format!("AC {ac}"));
    }
    let tran = inst.param("tran").trim();
    if !tran.is_empty() {
        parts.push(tran.to_string());
    }
    parts.join(" ")
}

/// Netlist with the generic technology and built-in models.
pub fn netlist(sch: &Schematic) -> Netlist {
    netlist_for(sch, &Tech::generic(), "")
}

/// Netlist for `tech`: MOS models map to the PDK devices ([`Tech::mos_device`]) and the PDK model
/// library is loaded at `corner` (empty = its default corner).
pub fn netlist_for(sch: &Schematic, tech: &Tech, corner: &str) -> Netlist {
    let conn = extract(sch);
    let mut warnings = conn.warnings.clone();
    let mut body = String::new();
    let (mut needs_mos, mut needs_diode, mut needs_bjt) = (false, false, false);
    // Generic per-L cards: (card name, base, L), and (element, card) for each device.
    let mut generic_cards: Vec<(String, String, f64)> = vec![];
    let mut generic: Vec<(String, String)> = vec![];

    let mut instances: Vec<&Instance> = sch.instances.iter().collect();
    instances.sort_by(|a, b| a.name.cmp(&b.name));

    let mut seen_names = std::collections::HashSet::new();
    for inst in instances {
        if inst.kind.spice_prefix().is_none() {
            continue;
        }
        let net = |pin: &str| conn.net_of(inst.id, pin).unwrap_or("?").to_string();
        let name = element_name(inst, tech);
        if !seen_names.insert(name.to_ascii_lowercase()) {
            warnings.push(format!("Duplicate instance name '{name}'"));
        }
        let line = match inst.kind {
            DeviceKind::Resistor => format!("{name} {} {} {}", net("p"), net("n"), inst.param("r")),
            DeviceKind::Capacitor => format!("{name} {} {} {}", net("p"), net("n"), inst.param("c")),
            DeviceKind::Inductor => format!("{name} {} {} {}", net("p"), net("n"), inst.param("l")),
            DeviceKind::VSource | DeviceKind::ISource => {
                format!("{name} {} {} {}", net("p"), net("n"), source_spec(inst))
            }
            DeviceKind::Diode => {
                needs_diode = true;
                format!("{name} {} {} {}", net("a"), net("k"), inst.param("model"))
            }
            DeviceKind::Npn | DeviceKind::Pnp => {
                needs_bjt = true;
                let area = inst.param("area").trim();
                let area = if area.is_empty() || area == "1" { String::new() } else { format!(" {area}") };
                format!("{name} {} {} {} {}{area}", net("c"), net("b"), net("e"), inst.param("model"))
            }
            DeviceKind::Vcvs => format!("{name} {} {} {} {} {}", net("p"), net("n"), net("cp"), net("cn"), inst.param("gain")),
            DeviceKind::Vccs => format!("{name} {} {} {} {} {}", net("p"), net("n"), net("cp"), net("cn"), inst.param("gm")),
            DeviceKind::Cccs => {
                format!("{name} {} {} {} {}", net("p"), net("n"), vsource_name(inst.param("vctl")), inst.param("gain"))
            }
            DeviceKind::Ccvs => {
                format!("{name} {} {} {} {}", net("p"), net("n"), vsource_name(inst.param("vctl")), inst.param("r"))
            }
            // A placed cell: its pins in subcircuit order. Simulation and LVS flatten the
            // hierarchy first ([`crate::sch_hier::flatten`]); this line is for netlist exports.
            DeviceKind::Cell => {
                let sub = inst.cell.as_ref().map_or("?".to_string(), |c| c.cell.clone());
                let nets: Vec<String> = inst.ports.iter().map(|(p, _)| net(p)).collect();
                format!("{name} {} {sub}", nets.join(" "))
            }
            DeviceKind::Nmos | DeviceKind::Pmos | DeviceKind::Nmos3 | DeviceKind::Pmos3 => {
                needs_mos = true;
                let bulk_pin = inst.pin_positions().into_iter().find(|(n, _)| *n == "b").map(|(_, p)| p);
                let bulk_floating = bulk_pin.is_some_and(|p| conn.unconnected_pins.contains(&p));
                let bulk = if bulk_floating { net("s") } else { net("b") };
                let model = match tech.mos_device(inst.kind.is_pmos(), inst.param("model")) {
                    Some(d) => d.name.clone(),
                    None => {
                        if !tech.devices.is_empty() {
                            warnings.push(format!("{name}: model '{}' is not a device of the technology", inst.param("model")));
                        }
                        inst.param("model").to_string()
                    }
                };
                match parse_spice(inst.param("l")).filter(|l| *l > 0.0) {
                    Some(l) if tech.models.is_none() && matches!(model.to_ascii_lowercase().as_str(), "nmos" | "pmos") => {
                        let base = model.to_ascii_lowercase();
                        let card = generic_card_name(&base, l);
                        if card != base {
                            if !generic_cards.iter().any(|(c, _, _)| *c == card) {
                                generic_cards.push((card.clone(), base, l));
                            }
                            generic.push((name.clone(), card));
                        }
                    }
                    _ => {}
                }
                let unit = tech.length_unit();
                let scaled = |k: &str, dim: i32| match (unit, parse_spice(inst.param(k))) {
                    (LengthUnit::Um, Some(v)) => fmt_num(v * unit.per_metre().powi(dim)),
                    _ => inst.param(k).to_string(),
                };
                let len = |k: &str| scaled(k, 1);
                let mut l = format!("{name} {} {} {} {bulk} {model} w={} l={}", net("d"), net("g"), net("s"), len("w"), len("l"));
                let m = inst.param("m").trim();
                if !m.is_empty() && m != "1" {
                    l += &format!(" m={m}");
                }
                for (k, dim) in [("ad", 2), ("as", 2), ("pd", 1), ("ps", 1)] {
                    if !inst.param(k).trim().is_empty() {
                        l += &format!(" {k}={}", scaled(k, dim));
                    }
                }
                // Threshold shift and mobility multiplier (BSIM instance parameters), set by
                // Monte Carlo mismatch: `M*.delvto`, `M*.mulu0`.
                for k in ["delvto", "mulu0"] {
                    let v = inst.param(k).trim();
                    if !v.is_empty() {
                        l += &format!(" {k}={v}");
                    }
                }
                l
            }
            DeviceKind::Ground | DeviceKind::Supply => unreachable!(),
        };
        body += &line;
        body.push('\n');
    }

    for p in &conn.unconnected_pins {
        let owner =
            sch.instances.iter().find(|i| i.pin_positions().iter().any(|(n, q)| q == p && !(*n == "b" && i.kind.is_mos())));
        if let Some(o) = owner {
            warnings.push(format!("Unconnected pin on {} at ({}, {})", o.name, p.x, p.y));
        }
    }

    match &tech.models {
        Some(m) => {
            if needs_mos {
                body += &m.spice_line(corner);
                body.push('\n');
            }
            if needs_diode && let Some(d) = DEFAULT_MODELS.lines().last() {
                body += d;
                body.push('\n');
            }
        }
        None if needs_mos || needs_diode => {
            body += DEFAULT_MODELS;
            body.push('\n');
        }
        None => {}
    }
    if needs_bjt {
        body += DEFAULT_BJT_MODELS;
        body.push('\n');
    }

    // Supply nets get no implicit source: users must place a voltage source.
    generic_cards.sort_by(|a, b| a.0.cmp(&b.0));
    let generic_cards = if tech.models.is_none() {
        generic_cards.iter().filter_map(|(card, base, l)| generic_card(base, card, *l)).collect()
    } else {
        generic.clear();
        vec![]
    };
    Netlist { body, warnings, conn, generic, generic_cards }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generic_models_scale_lambda_with_length() {
        let imp = crate::spice_import::import(
            "M1 a g 0 0 nmos w=1u l=180n\nM2 b g 0 0 nmos w=1u l=500n\nM3 c g 0 0 nmos w=1u l=1u\nV1 g 0 1\n.op\n",
            &Tech::generic(),
        )
        .unwrap();
        let nl = netlist_for(&imp.schematic, &Tech::generic(), "");
        assert!(!nl.body.contains("__l"), "the body keeps the drawn model names (CDL, LVS):\n{}", nl.body);
        let deck = nl.deck("t", &SimSetup::default());
        assert!(deck.contains("M1 a g 0 0 nmos__l180 w=1u l=180n"), "{deck}");
        assert!(deck.contains("M2 b g 0 0 nmos w=1u l=500n"), "the reference length keeps the base card:\n{deck}");
        let lam = |card: &str| crate::silicon::model_param(&deck, card, "lambda").unwrap();
        assert!((lam("nmos__l180") - 0.08 * 0.5 / 0.18).abs() < 1e-6);
        assert!((lam("nmos__l1000") - 0.04).abs() < 1e-6);
        // Editing the base card (silicon fits, process variation) carries over, lambda scaled.
        let d = crate::silicon::set_model_param(&deck, "nmos", "lambda", 0.1).unwrap();
        let d = crate::silicon::set_model_param(&d, "nmos", "vto", 0.5).unwrap();
        assert!((crate::silicon::model_param(&d, "nmos__l1000", "lambda").unwrap() - 0.05).abs() < 1e-9);
        assert!((crate::silicon::model_param(&d, "nmos__l180", "vto").unwrap() - 0.5).abs() < 1e-9);
    }
    use crate::geom::{Orient, Pt};

    #[test]
    fn three_terminal_mos_body_goes_to_its_bulk_net() {
        let mut s = Schematic::default();
        let n = s.add_instance(DeviceKind::Nmos3, Pt::new(0, 0), Orient::default());
        let p = s.add_instance(DeviceKind::Pmos3, Pt::new(10, 0), Orient::default());
        for (id, d, g, src) in [(n, "dn", "gn", "sn"), (p, "dp", "gp", "sp")] {
            for (pin, at) in s.instance(id).unwrap().pin_positions() {
                s.add_label(
                    match pin {
                        "d" => d,
                        "g" => g,
                        _ => src,
                    },
                    at,
                );
            }
        }
        s.instance_mut(p).unwrap().params.insert("bulk".into(), "vnw".into());
        let nl = netlist(&s);
        let line = |name: &str| nl.body.lines().find(|l| l.starts_with(name)).unwrap().to_string();
        assert!(line("M1").starts_with("M1 dn gn sn 0 "), "{}", nl.body);
        assert!(line("M2").starts_with("M2 dp gp sp vnw "), "{}", nl.body);
        assert!(!nl.warnings.iter().any(|w| w.contains("Unconnected")), "{:?}", nl.warnings);
    }

    #[test]
    fn simple_deck() {
        let mut s = Schematic::default();
        let v = s.add_instance(DeviceKind::VSource, Pt::new(0, 0), Orient::default());
        s.instance_mut(v).unwrap().params.insert("dc".into(), "5".into());
        s.add_instance(DeviceKind::Ground, Pt::new(0, 2), Orient::default());
        s.add_label("in", Pt::new(0, -2));
        let nl = netlist(&s);
        assert!(nl.body.contains("V1 in 0 DC 5"), "{}", nl.body);
        let deck = nl.deck("t", &SimSetup::default());
        assert!(deck.contains(".op"));
        assert!(deck.trim_end().ends_with(".end"));
    }

    #[test]
    fn formats() {
        let p = crate::examples::demo_project();
        let c = p.cell(&crate::project::CellRef::new("work", "cmos_inverter")).unwrap();
        let sch = c.schematic.as_ref().unwrap();
        let (spice, _) = write(sch, &p.tech, &c.sim, "work/cmos_inverter", Format::Spice);
        assert!(spice.contains(".end"));
        let (scs, _) = write(sch, &p.tech, &c.sim, "work/cmos_inverter", Format::Spectre);
        assert!(scs.contains("simulator lang=spectre") && scs.contains(") vsource"), "{scs}");
        let (cdl, _) = write(sch, &p.tech, &c.sim, "work/cmos_inverter", Format::Cdl);
        assert!(cdl.contains(".subckt work_cmos_inverter ") && cdl.contains("*.PININFO ") && cdl.contains(":B"), "{cdl}");
        assert!(!cdl.lines().any(|l| l.starts_with('V')), "{cdl}");
        assert_eq!("CDL".parse::<Format>(), Ok(Format::Cdl));
        assert!("verilog".parse::<Format>().is_err());
    }
}
