//! SPICE netlister: schematic + simulation setup -> SPICE deck.

use crate::connectivity::{Connectivity, extract};
use crate::schematic::{DeviceKind, Instance, Schematic};
use crate::sim_setup::SimSetup;

/// Generic default device models (level-1 style) used when no PDK models are given.
pub const DEFAULT_MODELS: &str = "\
.model nmos nmos (level=1 vto=0.45 kp=280u lambda=0.08 gamma=0.4 phi=0.8 tox=4n cgso=0.3n cgdo=0.3n cj=1m cjsw=0.3n)
.model pmos pmos (level=1 vto=-0.45 kp=70u lambda=0.1 gamma=0.4 phi=0.8 tox=4n cgso=0.3n cgdo=0.3n cj=1m cjsw=0.3n)
.model dmod d (is=1e-14 n=1 rs=10 cjo=1p)";

#[derive(Debug, Clone)]
pub struct Netlist {
    /// Element and model lines (no analyses / no .end).
    pub body: String,
    pub warnings: Vec<String>,
    pub conn: Connectivity,
}

impl Netlist {
    /// Full deck including the dot analyses, suitable for any SPICE simulator.
    pub fn deck(&self, title: &str, setup: &SimSetup) -> String {
        let mut s = format!("* {title}\n* Generated by IC Studio\n");
        s += &self.body;
        if !setup.extra.trim().is_empty() {
            s += "\n* --- user lines ---\n";
            s += setup.extra.trim();
            s += "\n";
        }
        s += &format!(".temp {}\n", setup.temp);
        for a in setup.enabled() {
            s += &format!(".{}\n", a.spice_command());
        }
        s += ".end\n";
        s
    }
}

pub(crate) fn spice_name(inst: &Instance) -> String {
    let prefix = inst.kind.spice_prefix().unwrap_or('X');
    let name = inst.name.trim().replace(' ', "_");
    if name.chars().next().is_some_and(|c| c.eq_ignore_ascii_case(&prefix)) { name } else { format!("{prefix}{name}") }
}

fn source_spec(inst: &Instance) -> String {
    let mut parts = vec![];
    let dc = inst.param("dc").trim();
    parts.push(format!("DC {}", if dc.is_empty() { "0" } else { dc }));
    let ac = inst.param("ac").trim();
    if !ac.is_empty() {
        parts.push(format!("AC {ac}"));
    }
    let tran = inst.param("tran").trim();
    if !tran.is_empty() {
        parts.push(tran.to_string());
    }
    parts.join(" ")
}

pub fn netlist(sch: &Schematic) -> Netlist {
    let conn = extract(sch);
    let mut warnings = conn.warnings.clone();
    let mut body = String::new();
    let mut needs_models = false;

    let mut instances: Vec<&Instance> = sch.instances.iter().collect();
    instances.sort_by(|a, b| a.name.cmp(&b.name));

    let mut seen_names = std::collections::HashSet::new();
    for inst in instances {
        if inst.kind.spice_prefix().is_none() {
            continue;
        }
        let net = |pin: &str| conn.net_of(inst.id, pin).unwrap_or("?").to_string();
        let name = spice_name(inst);
        if !seen_names.insert(name.to_ascii_lowercase()) {
            warnings.push(format!("Duplicate instance name '{name}'"));
        }
        let line = match inst.kind {
            DeviceKind::Resistor => format!("{name} {} {} {}", net("p"), net("n"), inst.param("r")),
            DeviceKind::Capacitor => format!("{name} {} {} {}", net("p"), net("n"), inst.param("c")),
            DeviceKind::Inductor => format!("{name} {} {} {}", net("p"), net("n"), inst.param("l")),
            DeviceKind::VSource | DeviceKind::ISource => {
                format!("{name} {} {} {}", net("p"), net("n"), source_spec(inst))
            }
            DeviceKind::Diode => {
                needs_models = true;
                format!("{name} {} {} {}", net("a"), net("k"), inst.param("model"))
            }
            DeviceKind::Nmos | DeviceKind::Pmos => {
                needs_models = true;
                let bulk_pin = inst.pin_positions().into_iter().find(|(n, _)| *n == "b").map(|(_, p)| p);
                let bulk_floating = bulk_pin.is_some_and(|p| conn.unconnected_pins.contains(&p));
                let bulk = if bulk_floating { net("s") } else { net("b") };
                let mut l = format!(
                    "{name} {} {} {} {bulk} {} w={} l={}",
                    net("d"),
                    net("g"),
                    net("s"),
                    inst.param("model"),
                    inst.param("w"),
                    inst.param("l")
                );
                let m = inst.param("m").trim();
                if !m.is_empty() && m != "1" {
                    l += &format!(" m={m}");
                }
                l
            }
            DeviceKind::Ground | DeviceKind::Supply => unreachable!(),
        };
        body += &line;
        body.push('\n');
    }

    for p in &conn.unconnected_pins {
        let owner = sch.instances.iter().find(|i| {
            i.pin_positions().iter().any(|(n, q)| q == p && !(*n == "b" && matches!(i.kind, DeviceKind::Nmos | DeviceKind::Pmos)))
        });
        if let Some(o) = owner {
            warnings.push(format!("Unconnected pin on {} at ({}, {})", o.name, p.x, p.y));
        }
    }

    if needs_models {
        body += DEFAULT_MODELS;
        body.push('\n');
    }

    // Supply nets get no implicit source: users must place a voltage source.
    Netlist { body, warnings, conn }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::geom::{Orient, Pt};

    #[test]
    fn simple_deck() {
        let mut s = Schematic::default();
        let v = s.add_instance(DeviceKind::VSource, Pt::new(0, 0), Orient::default());
        s.instance_mut(v).unwrap().params.insert("dc".into(), "5".into());
        s.add_instance(DeviceKind::Ground, Pt::new(0, 2), Orient::default());
        s.add_label("in", Pt::new(0, -2));
        let nl = netlist(&s);
        assert!(nl.body.contains("V1 in 0 DC 5"), "{}", nl.body);
        let deck = nl.deck("t", &SimSetup::default());
        assert!(deck.contains(".op"));
        assert!(deck.trim_end().ends_with(".end"));
    }
}
